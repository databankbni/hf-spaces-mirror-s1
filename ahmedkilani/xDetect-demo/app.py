EXAMPLES = [
    ["The implementation of advanced neural network architectures has significantly enhanced the capabilities of modern natural language processing systems, enabling more sophisticated understanding of contextual semantics.", "English"],
    ["Floods hit southern regions after days of heavy rainfall, displacing thousands of residents. Emergency services were deployed overnight and local authorities urged people to avoid low-lying areas.", "English"],
    ["Die Klimakrise erfordert sofortige Maßnahmen auf globaler Ebene, da die Temperaturen weltweit weiter ansteigen und die Folgen für Mensch und Natur immer gravierender werden.", "German"],
    ["يُعدّ الذكاء الاصطناعي من أبرز التقنيات التي شهدها العالم في العقود الأخيرة، إذ أحدث ثورة حقيقية في مختلف المجالات الحياتية.", "Arabic"],
]

with gr.Blocks(title="xDetect — AI Text Detector", theme=gr.themes.Soft()) as demo:
    gr.Markdown(DESCRIPTION)

    with gr.Row():
        with gr.Column(scale=3):
            text_input = gr.Textbox(
                label="Input Text",
                placeholder="Paste news or article text here (English, German, or Arabic)...",
                lines=8,
            )
            lang_choice = gr.Radio(
                choices=["Auto-detect", "English", "German", "Arabic"],
                value="Auto-detect",
                label="Language",
            )
            submit_btn = gr.Button("🔍 Detect", variant="primary", size="lg")

        with gr.Column(scale=2):
            verdict_out = gr.Markdown(label="Verdict", value="")
            detail_out  = gr.Markdown(label="Details", value="")
            _hidden     = gr.Markdown(visible=False)

    gr.Examples(examples=EXAMPLES, inputs=[text_input, lang_choice], label="Example texts")

    submit_btn.click(predict, [text_input, lang_choice], [verdict_out, detail_out, _hidden])
    text_input.submit(predict, [text_input, lang_choice], [verdict_out, detail_out, _hidden])

demo.launch()