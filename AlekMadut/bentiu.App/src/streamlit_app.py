def predict_flood(image, model, alert_system):
    """Run prediction and return results with alert"""

    # Ensure image has batch dimension
    if len(image.shape) == 3:
        image = image[np.newaxis, ...]

    # Time the prediction
    start = time.time()
    prediction = model.predict(image, verbose=0)
    inference_time = (time.time() - start) * 1000  # ms

    # Calculate metrics
    flood_mask = (prediction[0] > 0.5).astype(np.float32)
    flood_percentage = flood_mask.mean() * 100

    # Get alert
    alert = alert_system.get_alert(flood_percentage)

    return {
        'prediction': prediction[0],
        'flood_mask': flood_mask,
        'flood_percentage': flood_percentage,
        'alert': alert,
        'inference_time': inference_time
    }

