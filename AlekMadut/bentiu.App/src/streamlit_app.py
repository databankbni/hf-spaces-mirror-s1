class CombinedCallback(Callback):
    def __init__(self, alert_cb, radio_cb, dashboard_cb):
        super().__init__()
        self.alert_cb = alert_cb
        self.radio_cb = radio_cb
        self.dashboard_cb = dashboard_cb
