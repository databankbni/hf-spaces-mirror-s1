class FloodDataGenerator:
    """
    Generates realistic synthetic SAR imagery for flood detection.
    Simulates Sentinel-1 VV/VH backscatter with terrain features.
    """

    def __init__(self, image_size=(128, 128)):
        self.image_size = image_size
        self.rng = np.random.RandomState(42)

    def create_terrain_features(self):
        """Generate synthetic terrain with HAND and Slope"""
        h, w = self.image_size

        # Create base terrain
        x = np.linspace(-3, 3, w)
        y = np.linspace(-3, 3, h)
        X, Y = np.meshgrid(x, y)

        # Complex terrain
        elevation = (
            np.sin(X * 1.5) * np.cos(Y * 1.5) * 2.5 +
            np.sin(2.5*X + 1) * np.sin(2.5*Y) * 2.0 +
            np.cos(3*X) * np.sin(3*Y) * 1.5 +
            X * 0.4 + Y * 0.4 +
            self.rng.randn(h, w) * 0.4
        )

        # Height Above Nearest Drainage (rivers at 20th percentile)
        river_level = np.percentile(elevation, 20)
        hand = elevation - river_level
        hand = np.clip(hand, 0, 8)

        # Calculate slope
        gy, gx = np.gradient(elevation)
        slope = np.sqrt(gx**2 + gy**2)
        slope = np.clip(slope, 0, 4)

        return hand, slope, elevation

    def simulate_sar_backscatter(self, is_water_mask, is_urban_mask=None, elevation=None):
        """
        Simulate Sentinel-1 VV and VH backscatter.

        WATER:   VV = -23 ± 3 dB (specular reflection away from sensor)
                 VH = -28 ± 3 dB (very low cross-polarization)

        LAND:    VV = -10 ± 5 dB (rough surface scattering)
                 VH = -16 ± 4 dB

        URBAN:   VV = 0 ± 4 dB (double bounce from buildings)
                 VH = -8 ± 3 dB
        """
        h, w = self.image_size

        # Base backscatter
        vv_base = np.full((h, w), -10.0)
        vh_base = np.full((h, w), -16.0)

        # Water areas - very dark in SAR
        vv_base[is_water_mask] = -23.0
        vv_base[is_water_mask] += self.rng.randn(np.sum(is_water_mask)) * 3 # Add random noise
        vh_base[is_water_mask] = -28.0
        vh_base[is_water_mask] += self.rng.randn(np.sum(is_water_mask)) * 3 # Add random noise

        # Urban areas - bright in SAR (double bounce)
        if is_urban_mask is not None:
            vv_base[is_urban_mask] = 0.0
            vv_base[is_urban_mask] += self.rng.randn(np.sum(is_urban_mask)) * 4 # Add random noise
            vh_base[is_urban_mask] = -8.0
            vh_base[is_urban_mask] += self.rng.randn(np.sum(is_urban_mask)) * 3 # Add random noise

        # Add elevation-based variation (higher = slightly brighter)
        if elevation is not None:
            elev_normalized = (elevation - elevation.min()) / (elevation.max() - elevation.min() + 1e-6)
            vv_base += elev_normalized * 3
            vh_base += elev_normalized * 2

        # Speckle noise (gamma distribution - characteristic of SAR)
        speckle_vv = self.rng.gamma(shape=5, scale=0.4, size=(h, w))
        speckle_vh = self.rng.gamma(shape=5, scale=0.35, size=(h, w))

        vv = vv_base + speckle_vv
        vh = vh_base + speckle_vh

        # Thermal noise
        vv += self.rng.randn(h, w) * 0.4
        vh += self.rng.randn(h, w) * 0.3

        return vv, vh

    def create_flood_scenario(self):
        """Create complete flood scenario with pre/post flood states"""
        h, w = self.image_size

        # Generate terrain
        hand, slope, elevation = self.create_terrain_features()

        # Permanent water (lakes, rivers) - HAND < random threshold
        permanent_water = (hand < self.rng.uniform(0.2, 0.6))

        # Urban/camp areas (simulated settlements)
        urban_mask = np.zeros((h, w), dtype=bool)
        num_urban = self.rng.randint(1, 3)
        for _ in range(num_urban):
            cx, cy = self.rng.randint(25, w-25), self.rng.randint(25, h-25)
            rx, ry = self.rng.randint(6, 14), self.rng.randint(6, 14)
            Y_grid, X_grid = np.ogrid[:h, :w]
            urban_mask |= ((X_grid - cx)**2 / rx**2 + (Y_grid - cy)**2 / ry**2) < 1

        # Pre-flood: only permanent water
        pre_flood_water = permanent_water.copy()

        # Post-flood: flood expands based on HAND threshold
        flood_level = self.rng.uniform(0.6, 2.5)
        post_flood_water = (hand < flood_level) | permanent_water

        # Generate SAR imagery
        pre_vv, pre_vh = self.simulate_sar_backscatter(pre_flood_water, urban_mask, elevation)
        post_vv, post_vh = self.simulate_sar_backscatter(post_flood_water, urban_mask, elevation)

        # Change features (positive = water appeared)
        vv_diff = pre_vv - post_vv
        vh_diff = pre_vh - post_vh

        # 8-channel stack
        input_stack = np.stack([
            pre_vv,
            post_vv,
            vv_diff,
            pre_vh,
            post_vh,
            vh_diff,
            hand,
            slope
        ], axis=-1)

        # Normalize to [0, 1]
        input_stack = self.normalize_stack(input_stack)

        # Flood mask (newly flooded areas, excluding permanent water)
        flood_mask = (post_flood_water & ~pre_flood_water).astype(np.float32)

        # Urban areas are not flooded (challenge for model)
        flood_mask[urban_mask] = 0.0

        return input_stack, flood_mask, {
            'permanent_water': permanent_water,
            'urban': urban_mask,
            'elevation': elevation,
            'hand': hand
        }

    def normalize_stack(self, stack):
        """Min-max normalize each channel to [0, 1]"""
        normalized = np.zeros_like(stack)
        for c in range(stack.shape[-1]):
            ch = stack[..., c]
            ch_min, ch_max = ch.min(), ch.max()
            if ch_max > ch_min:
                normalized[..., c] = (ch - ch_min) / (ch_max - ch_min)
            else:
                normalized[..., c] = ch
        return normalized

    def generate_dataset(self, n_samples, verbose=True):
        """Generate dataset with progress tracking"""
        X, y = [], []
        metadata = []

        for i in range(n_samples):
            img, mask, meta = self.create_flood_scenario()
            X.append(img)
            y.append(mask)
            metadata.append(meta)

            if verbose and (i + 1) % 20 == 0:
                print(f"  ⏳ Generated {i+1}/{n_samples} flood scenarios...")

        return np.array(X), np.array(y)[..., np.newaxis], metadata

