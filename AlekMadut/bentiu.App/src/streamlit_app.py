def dice_coefficient(y_true, y_pred, smooth=1e-6):
    """Dice Score: Measures overlap between prediction and ground truth"""
    y_true_f = K.flatten(y_true)
    y_pred_f = K.flatten(y_pred)
    intersection = K.sum(y_true_f * y_pred_f)
    return (2. * intersection + smooth) / (K.sum(y_true_f) + K.sum(y_pred_f) + smooth)

def iou_metric(y_true, y_pred, smooth=1e-6):
    """Intersection over Union (Jaccard Index): Key segmentation metric"""
    y_true_f = K.flatten(y_true)
    y_pred_f = K.flatten(y_pred)
    intersection = K.sum(y_true_f * y_pred_f)
    union = K.sum(y_true_f) + K.sum(y_pred_f) - intersection
    return (intersection + smooth) / (union + smooth)

def precision_metric(y_true, y_pred):
    """Precision: What fraction of predicted floods are real?"""
    y_true_f = K.flatten(y_true)
    y_pred_f = K.flatten(y_pred)
    true_positives = K.sum(K.round(y_true_f) * K.round(y_pred_f))
    predicted_positives = K.sum(K.round(y_pred_f))
    return true_positives / (predicted_positives + K.epsilon())

def recall_metric(y_true, y_pred):
    """Recall: What fraction of real floods did we detect?"""
    y_true_f = K.flatten(y_true)
    y_pred_f = K.flatten(y_pred)
    true_positives = K.sum(K.round(y_true_f) * K.round(y_pred_f))
    possible_positives = K.sum(K.round(y_true_f))
    return true_positives / (possible_positives + K.epsilon())

def f1_metric(y_true, y_pred):
    """F1 Score: Harmonic mean of precision and recall"""
    precision = precision_metric(y_true, y_pred)
    recall = recall_metric(y_true, y_pred)
    return 2 * ((precision * recall) / (precision + recall + K.epsilon()))

def combined_loss(y_true, y_pred):
    """
    Combined Loss = BCE + Dice Loss
    BCE: Pixel-wise accuracy
    Dice: Region overlap quality (better for imbalanced flood/no-flood classes)
    """
    bce = tf.keras.losses.binary_crossentropy(y_true, y_pred)
    dice = 1 - dice_coefficient(y_true, y_pred)
    return bce + 0.5 * dice

