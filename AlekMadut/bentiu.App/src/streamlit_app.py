def convolution_block(x, filters, size, strides=(1,1), padding='same',
                      dilation_rate=1, activation=True):
    """Standard convolution block with BN and optional activation"""
    x = Conv2D(filters, size, strides=strides, padding=padding,
               dilation_rate=dilation_rate)(x)
    x = BatchNormalization()(x)
    if activation:
        x = Activation('relu')(x)
    return x

def residual_block(x, filters):
    """Residual block with skip connection"""
    shortcut = Conv2D(filters, 1, padding='same')(x)
    shortcut = BatchNormalization()(shortcut)

    x = convolution_block(x, filters, 3)
    x = Dropout(0.1)(x)
    x = convolution_block(x, filters, 3, activation=False)

    x = Add()([x, shortcut])
    x = Activation('relu')(x)
    return x

def ASPP_block(x, filters=128):
    """
    Atrous Spatial Pyramid Pooling
    Captures water features at multiple scales:
    - Small ponds (dilation=6)
    - Medium lakes (dilation=12)
    - Large flood plains (dilation=18)
    - Global context (image pooling)
    """
    input_shape = x.shape[1:3]

    # 1x1 convolution
    c1 = convolution_block(x, filters, 1)

    # Multi-scale atrous convolutions
    c3 = convolution_block(x, filters, 3, dilation_rate=6)
    c6 = convolution_block(x, filters, 3, dilation_rate=12)
    c9 = convolution_block(x, filters, 3, dilation_rate=18)

    # Global average pooling branch
    pool = GlobalAveragePooling2D()(x)
    pool = Reshape((1, 1, x.shape[-1]))(pool)
    pool = Conv2D(filters, 1, padding='same')(pool)
    pool = BatchNormalization()(pool)
    pool = Activation('relu')(pool)
    pool = UpSampling2D(size=input_shape, interpolation='bilinear')(pool)

    # Concatenate all branches
    x = Concatenate()([c1, c3, c6, c9, pool])
    x = Conv2D(filters, 1, padding='same')(x)
    x = BatchNormalization()(x)
    x = Activation('relu')(x)
    x = Dropout(0.1)(x)

    return x

def DeepLabV3Plus_Flood(input_shape=(128, 128, 8)):
    """
    DeepLabV3+ Architecture for Flood Segmentation

    Encoder: Progressive feature extraction
    - 4 levels of downsampling for hierarchical features
    - Residual connections for gradient flow

    ASPP Bridge: Multi-scale water detection
    - Detects small/local floods AND large/regional floods

    Decoder: Precise boundary recovery
    - Skip connections from encoder preserve spatial details
    - Progressive upsampling for accurate water boundaries
    """
    inputs = Input(shape=input_shape, name='8_channel_SAR_input')

    # ===== ENCODER: Feature Extraction =====
    # Level 1: 128x128 -> 64x64
    e1 = convolution_block(inputs, 32, 7, strides=2)
    e1 = residual_block(e1, 32)

    # Level 2: 64x64 -> 32x32
    e2 = convolution_block(e1, 64, 3, strides=2)
    e2 = residual_block(e2, 64)

    # Level 3: 32x32 -> 16x16
    e3 = convolution_block(e2, 128, 3, strides=2)
    e3 = residual_block(e3, 128)

    # Level 4: 16x16 -> 8x8
    e4 = convolution_block(e3, 256, 3, strides=2)
    e4 = residual_block(e4, 256)

    # ===== ASPP BRIDGE: Multi-Scale Context =====
    bridge = ASPP_block(e4, 128)

    # ===== DECODER: Boundary Refinement =====
    # Upsample: 8x8 -> 16x16
    d1 = UpSampling2D(size=2, interpolation='bilinear')(bridge)
    d1 = Concatenate()([d1, e3])  # Skip connection
    d1 = convolution_block(d1, 128, 3)
    d1 = residual_block(d1, 128)

    # Upsample: 16x16 -> 32x32
    d2 = UpSampling2D(size=2, interpolation='bilinear')(d1)
    d2 = Concatenate()([d2, e2])  # Skip connection
    d2 = convolution_block(d2, 64, 3)
    d2 = residual_block(d2, 64)

    # Upsample: 32x32 -> 64x64
    d3 = UpSampling2D(size=2, interpolation='bilinear')(d2)
    d3 = Concatenate()([d3, e1])  # Skip connection
    d3 = convolution_block(d3, 32, 3)
    d3 = residual_block(d3, 32)

    # Upsample: 64x64 -> 128x128
    d4 = UpSampling2D(size=2, interpolation='bilinear')(d3)
    d4 = convolution_block(d4, 16, 3)

    # Output: Binary flood mask
    outputs = Conv2D(1, 1, padding='same', activation='sigmoid',
                    name='flood_probability')(d4)

    model = Model(inputs=inputs, outputs=outputs, name='Bentiu_FloodWatch_DeepLabV3_NoPlus')
    return model

