    def set_model(self, model):
        super().set_model(model)
        self.alert_cb.set_model(model)
        self.dashboard_cb.set_model(model)

    def on_epoch_end(self, epoch, logs=None):
        # Run alert system
        self.alert_cb.on_epoch_end(epoch, logs)

        # Check if alert level changed and trigger radio
        if self.alert_cb.current_level != self.last_alert_level:
            if self.alert_cb.current_level != "\ud83d\udfe2 GREEN":
                self.radio_cb.broadcast(self.alert_cb.current_level)
            self.last_alert_level = self.alert_cb.current_level

        # Run dashboard
        self.dashboard_cb.on_epoch_end(epoch, logs)

