from datetime import date


def get_system_prompt(web_search: bool = True) -> str:
    today = date.today().strftime("%Y年%m月%d日")
    prompt = _SYSTEM_PROMPT_TEMPLATE.format(today=today)
    if web_search:
        prompt += _WEB_SEARCH_SECTION
    return prompt


